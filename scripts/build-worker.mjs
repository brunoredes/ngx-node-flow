// Bundles the renderer worker into a string constant, because ng-packagr cannot emit
// `new Worker(new URL(...))` entries and app builders don't transform workers inside node_modules.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const lib = 'projects/ngx-node-flow/src/lib';
const { outputFiles } = await build({
  entryPoints: [`${lib}/renderer.worker.ts`],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2022',
  write: false,
});
writeFileSync(
  `${lib}/worker-source.ts`,
  `// Generated by scripts/build-worker.mjs. Do not edit.\nexport const WORKER_SOURCE = ${JSON.stringify(outputFiles[0].text)};\n`,
);
